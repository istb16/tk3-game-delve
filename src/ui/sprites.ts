// --- 公開 API ----------------------------------------------------------------

export { PLAYER };

export function playerSpriteId(frame: number): string {
  return `sp-player-${frame}`;
}

export function enemySpriteId(kind: EnemyKind, frame: number): string {
  return `sp-${ENEMY_SPRITE_NAME[kind]}-${frame}`;
}

export function tileSpriteId(kind: TileKind): string {
  return `sp-${kind}-0`;
}

export function itemSpriteId(itemId: ItemId): string {
  return `sp-${itemId}-0`;
}

/** 床に落ちている物のスプライト。装備は種別（武器/防具/指輪）で描き分ける。 */
export function entitySpriteId(entity: Entity): string {
  switch (entity.payload.type) {
    case 'item':
      return itemSpriteId(entity.payload.itemId);
    case 'gold':
      return 'sp-gold-0';
    case 'chest':
      return 'sp-chest-0';
    case 'event':
      // イベントは「怪しい石」として一律に描く。中身が見えていたら賭けにならない。
      return 'sp-shrine-0';
    case 'equipment':
      return `sp-${entity.payload.equipment.slot}-0`;
  }
}

/** <defs> に入れるスプライトの一覧。同じ絵を二重に定義しない。 */
export function allSprites(): { id: string; def: SpriteDef; frame: number }[] {
  const out: { id: string; def: SpriteDef; frame: number }[] = [];
  for (const [name, def] of Object.entries(SPRITES)) {
    def.frames.forEach((_, frame) => out.push({ id: `sp-${name}-${frame}`, def, frame }));
  }
  return out;
}

